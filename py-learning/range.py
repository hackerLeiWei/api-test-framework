
"""
range() 是一个不可变的序列类型。它存储 start、stop、step。当打印时，它只是打印这个描述。它与列表/元组不同，不会展开。
为什么 print 显示 range(1, 10)？：解释 range 是一个惰性求值对象。print() 调用 __str__ 或 __repr__，它们显示构造参数，而非具体元素（以节省内存并显示意图）

迭代使用 __iter__()，它产生序列中的实际项。range(1,10) 的项是 1 到 9，因为 stop 是独占的。
为什么是半开区间？ 便于处理 0 索引，range(n) 准确产生 n 个元素（0 到 n-1），并且容易拼接 range(0,5) 和 range(5,10)。

为什么 for 会给出 1 到 9？：解释迭代器协议。range 对象在迭代时逐个生成值。Python 的 range 使用半开区间 [start, stop)（不包括右端点），这是编程中的标准惯例（零基索引，长度计算简单）。

如何显示数字？：展示如何实际查看元素（list(range(1,10)) 或 tuple(...)）。
"""
r1 = range(0,10)
print(f"直接打印: {r1}")
print(f"转换为列表: {list(r1)}")
print(f"转换为元组: {tuple(r1)}")